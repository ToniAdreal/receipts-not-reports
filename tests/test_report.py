"""M5 guards: the report's headline numbers must match the real sweep.

Every number cited in report.md is checked against
experiments/results/sweep.json (regenerated by experiments/run_sweep.py
from real runs). If the sweep changes, the report must be re-drafted;
these tests fail loudly instead of letting a stale number ship.
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
REPORT = APP / "report" / "report.md"
SWEEP = APP / "experiments" / "results" / "sweep.json"

TEXT = REPORT.read_text()
SWEEP_DATA = json.loads(SWEEP.read_text())
ROWS = SWEEP_DATA["rows"]


def _abstract_words() -> int:
    abstract = TEXT.split("## Abstract")[1].split("## 1.")[0]
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’.-]*", abstract))


def test_abstract_word_count_in_template_range():
    assert 150 <= _abstract_words() <= 250, _abstract_words()


def test_required_sections_present():
    for section in [
        "## 1. Introduction",
        "## 2. Related Work",
        "## 3. Methods",
        "## 4. Results",
        "## 5. Discussion and Limitations",
        "## 6. Conclusion",
        "## Code and Data",
        "## Author Contributions",
        "## References",
        "## Appendix A. Limitations and Dual-Use / Ethical Considerations",
        "## Appendix B.",
        "## LLM Usage Statement",
    ]:
        assert section in TEXT, section


def test_preexisting_labelled():
    assert "PREEXISTING" in TEXT
    assert "VerifyGate" in TEXT


def _totals():
    events = sum(r["monitors"]["evidence-gated"]["detected"] for r in ROWS)
    # events per row: sum the per-kind event counts (rows carry no top-level total)
    total_events = 0
    by_kind = defaultdict(lambda: [0, 0, 0, 0])  # ev_det, ev_tot, nv_det, nv_tot
    spoof_claims = 0
    spoof_accepted = {"evidence-gated": 0, "naive": 0}
    for r in ROWS:
        for mon, key in (("evidence-gated", 0), ("naive", 2)):
            for kind, bk in r["monitors"][mon]["by_kind"].items():
                by_kind[kind][key] += bk["detected"]
                by_kind[kind][key + 1] += bk["events"]
        total_events += sum(
            bk["events"]
            for bk in r["monitors"]["evidence-gated"]["by_kind"].values()
        )
        spoof_claims += r["monitors"]["naive"]["spoofed_claims"]
        for mon in spoof_accepted:
            spoof_accepted[mon] += r["monitors"][mon][
                "spoofed_claims_accepted"
            ]
    naive_detected = sum(r["monitors"]["naive"]["detected"] for r in ROWS)
    return {
        "events": total_events,
        "evidence_detected": events,
        "naive_detected": naive_detected,
        "by_kind": dict(by_kind),
        "spoof_claims": spoof_claims,
        "spoof_accepted": spoof_accepted,
    }


def test_headline_numbers_match_sweep():
    t = _totals()
    assert t["events"] == 450
    assert t["evidence_detected"] == 446
    assert t["naive_detected"] == 251
    assert t["spoof_claims"] == 85
    assert t["spoof_accepted"]["evidence-gated"] == 0
    assert t["spoof_accepted"]["naive"] == 85
    for needle in [
        "446 of 450",
        "251 of 450",
        "85 spoofed claims",
        "30-run sweep",
    ]:
        assert needle in TEXT, needle


def test_per_kind_numbers_match_sweep():
    t = _totals()
    expected = {
        "delete": (129, 129, 120),
        "edit": (90, 90, 0),
        "spoof": (90, 90, 0),
        "rename": (137, 141, 131),
    }
    for kind, (ev_det, ev_tot, nv_det) in expected.items():
        got = t["by_kind"][kind]
        assert (got[0], got[1]) == (ev_det, ev_tot), kind
        assert got[2] == nv_det, kind
    for needle in [
        "129 (1.00)",
        "90 (1.00)",
        "137 (0.97)",
        "120 (0.93)",
        "131 (0.93)",
    ]:
        assert needle in TEXT, needle


def test_no_unverifiable_figure_path_leaks():
    # The report source must keep a relative figure path (build_pdf.py
    # resolves it); no absolute build-machine path may leak into the text.
    assert "file://" not in TEXT
    assert "/home/" not in TEXT
    assert "](sweep.png)" in TEXT
